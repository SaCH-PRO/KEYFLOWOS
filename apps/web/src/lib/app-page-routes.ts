const STATIC = new Set(APP_PAGE_ROUTES.filter((r) => !r.includes("[")));
const DYNAMIC = APP_PAGE_ROUTES.filter((r) => r.includes("[")).map((r) => r.split("/"));

/** True when `path` (query and hash ignored) opens a page under /app. */
export function isAppPage(path: string): boolean {
  const clean = path.split(/[?#]/)[0]!.replace(/\/+$/, "") || "/";
  if (STATIC.has(clean)) return true;
  const parts = clean.split("/");
  return DYNAMIC.some((route) => route.length === parts.length && route.every((seg, i) => /^\[[^\]]+\]$/.test(seg) || seg === parts[i]));
}
