/**
 * The gate was pointing the wrong way.
 *
 * nav-destinations.spec.ts asserts every nav href resolves to a page. Nothing
 * asserted the converse — that every page has a door. So the product accumulated
 * finished, tested, styled screens that no user could navigate to, and the nav
 * kept being repaired one entry at a time: 9857a397, 1ea8c4b7, 21f512d5,
 * b43a3d4c, 83588f95. Five consecutive commits treating a symptom.
 *
 * Measured here: 74 of 203 routes under /app are outside the nav — 36%.
 * Of those, 47 are real screens, several of them substantial: /app/finance/tax
 * (622 lines), /app/time-tracking (600), /app/crm/data-quality (560),
 * /app/finance/reconciliation (486). Work that produced zero user value and
 * carries full maintenance cost.
 *
 * Two of those doors were opened this week only because someone ran the app:
 * inventory sat behind a redirect to a commerce tab that did not exist, and
 * payments behind a permanent 308 into the same hole. Neither was findable by
 * reading source. This spec is the version that does not need a browser.
 *
 * WHY THE RULE IS BINARY
 * ---------------------
 * The first design had three arms: nav-reachable, OR linked from a reachable
 * page, OR allowlisted. The middle arm was measured and dropped. Navigation in
 * this app is 39 static <Link href="/app/…">, 222 dynamic href={…} and 293
 * router.push(…) — roughly 93% computed. A static link-graph would miss most
 * edges and report reachable screens as orphans, and a noisy gate gets disabled.
 * A disabled gate is worse than none.
 *
 * So: nav-reachable, or an explicit entry with a reason. No inference.
 *
 * REACHABILITY RULE
 * -----------------
 * A route is nav-reachable if the nav lands you in its subtree — the href equals
 * it, is a prefix of it, or it is a prefix of an href. /app/settings is reachable
 * because /app/settings/team is a nav item; /app/settings/billing is reachable
 * because /app/settings is. This is deliberately generous: the gate exists to
 * catch whole clusters with no way in, not to audit tab strips.
 *
 * THE ALLOWLIST IS THE BACKLOG
 * ----------------------------
 * Three reasons, and only three:
 *
 *   detail-route-of:<route>   a dynamic page reached from its parent record
 *   deliberately-unlinked     a redirect shim or re-export; a forwarding
 *                             address, not a destination
 *   todo-connect              a real screen with no door. THIS IS WORK, not an
 *                             exemption. 7 entries today (47 -> 39 -> 33 ->
 *                             7; 29 doors opened 2026-08-08). The number
 *                             should only go down.
 *   fabricated-do-not-link    a screen that simulates a network request and
 *                             renders invented numbers. Connecting it is the
 *                             WRONG fix — see no-fabricated-screens.spec.ts,
 *                             which fails if one reaches the nav. It needed
 *                             its own reason because 'todo-connect' reads as
 *                             an instruction to open the door, and three of
 *                             these were sitting in that list.
 *
 * Adding a page without a nav entry now requires writing down which of those it
 * is, which is the whole point.
 */
