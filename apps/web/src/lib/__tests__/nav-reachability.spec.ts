/** Every directory under app/app that renders a page. */
function routes(): string[] {
  const found: string[] = [];
  const walk = (dir: string, prefix: string) => {
    for (const entry of fs.readdirSync(dir)) {
      const full = path.join(dir, entry);
      if (!fs.statSync(full).isDirectory()) continue;
      const route = `${prefix}/${entry}`;
      if (fs.existsSync(path.join(full, 'page.tsx'))) found.push(route);
      walk(full, route);
    }
  };
  walk(APP, '/app');
  return found.sort();
}

function navHrefs(): string[] {
  const src = fs.readFileSync(path.join(WEB_SRC, 'lib', 'nav-config.ts'), 'utf8');
  return [...new Set([...src.matchAll(/href: "(\/app\/[^"]*)"/g)].map((m) => m[1].split('?')[0]))];
}

/** Does the nav land you anywhere in this route's subtree? */
function navReachable(route: string, hrefs: string[]): boolean {
  return hrefs.some(
    (h) =>
      route === h ||
      route.startsWith(h.replace(/\/$/, '') + '/') ||
      h.startsWith(route.replace(/\/$/, '') + '/'),
  );
}

describe('every screen has a door, or a written reason it does not', () => {
  const all = routes();
  const hrefs = navHrefs();

  it('finds both sides', () => {
    expect(all.length).toBeGreaterThan(150);
    expect(hrefs.length).toBeGreaterThan(30);
  });

  it('no page is unreachable and undeclared', () => {
    const undeclared = all.filter((r) => !navReachable(r, hrefs) && !ORPHANED_BY_DESIGN[r]);

    expect(
      undeclared,
      'these render a page that no nav path reaches, and say nothing about why. Add a nav ' +
        'entry, or an ORPHANED_BY_DESIGN entry saying whether it is a detail route, a ' +
        'deliberate shim, or work still to do',
    ).toEqual([]);
  });

  it('the allowlist names only routes that still exist', () => {
    // A stale exemption is where the next orphan hides — the same failure as
    // ConversationThread sitting in BUSINESS_ID_MODELS after the model was
    // dropped.
    const gone = Object.keys(ORPHANED_BY_DESIGN).filter((r) => !all.includes(r));

    expect(gone, `these no longer exist — remove them: ${gone.join(', ')}`).toEqual([]);
  });

  it('the allowlist does not exempt routes that are now in the nav', () => {
    // When a door opens, the entry has to go. Otherwise the backlog never
    // visibly shrinks and the list stops meaning anything.
    const nowReachable = Object.keys(ORPHANED_BY_DESIGN).filter((r) => navReachable(r, hrefs));

    expect(
      nowReachable,
      `these are reachable now — delete their entries: ${nowReachable.join(', ')}`,
    ).toEqual([]);
  });

  it('every detail-route-of points at a route that exists', () => {
    const dangling = Object.entries(ORPHANED_BY_DESIGN)
      .filter(([, why]) => why.startsWith('detail-route-of:'))
      .map(([r, why]) => [r, why.slice('detail-route-of:'.length)] as const)
      .filter(([, parent]) => !all.includes(parent));

    expect(dangling.map(([r, p]) => `${r} -> ${p}`), 'parent route is gone').toEqual([]);
  });

  it('the connect backlog does not grow', () => {
    // A ratchet. 47 is today's count; this fails if it rises, which makes
    // "ship a screen and wire it later" a decision someone has to argue for.
    const todo = Object.values(ORPHANED_BY_DESIGN).filter((w) => w === 'todo-connect');

    expect(
      todo.length,
      'more screens are now unreachable than when this gate was written. Connect one, or ' +
        'delete one, before adding another',
    ).toBeLessThanOrEqual(39);
  });
});
