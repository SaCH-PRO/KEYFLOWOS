import fs from 'node:fs';
import path from 'node:path';

const WEB_SRC = path.join(__dirname, '..', '..');
const APP = path.join(WEB_SRC, 'app', 'app');

type Reason =
  | `detail-route-of:${string}`
  | 'deliberately-unlinked'
  | 'todo-connect'
  | 'fabricated-do-not-link';

